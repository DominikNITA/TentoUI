<#
.SYNOPSIS
  Regenerates src/TentoUI/tailwind/tentoui.classes.txt - the Tailwind class manifest shipped in the TentoUI package.

.DESCRIPTION
  TentoUI ships compiled assemblies, so consuming apps cannot point Tailwind at the component .razor sources.
  Instead the package ships a plain-text manifest of every candidate utility class used by the components.
  Consumers add it as a Tailwind @source. Run this script whenever component markup changes.
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root 'src/TentoUI'
$out = Join-Path $src 'tailwind/tentoui.classes.txt'
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null

$files = Get-ChildItem $src -Recurse -Include *.razor, *.cs |
    Where-Object { $_.FullName -notmatch '[\\/](bin|obj)[\\/]' }

# Split on anything that cannot be part of a Tailwind candidate, then keep tokens that look like utilities.
$pattern = '[A-Za-z!@\-][A-Za-z0-9:\-\/\[\]\.%_!#,()=&>*]*'
$tokens = foreach ($f in $files) {
    [regex]::Matches((Get-Content $f.FullName -Raw), $pattern) | ForEach-Object { $_.Value }
}
$unique = $tokens | Where-Object { $_.Length -ge 2 -and $_.Length -le 100 } | Sort-Object -Unique -CaseSensitive

$header = "# Generated by scripts/generate-tentoui-classes.ps1 - do not edit. Tailwind @source manifest for TentoUI."
Set-Content -Path $out -Value (@($header) + $unique) -Encoding utf8
Write-Host "Wrote $($unique.Count) candidate tokens to $out"
